// Package native is Brick's own x86-64 backend. It emits System V AMD64
// assembly directly, so the compiler — not a C compiler — chooses the
// instructions. The assembler (as) only encodes; the linker (cc) only links
// libc. This is the first step toward optimizing using facts C cannot express
// (no aliasing, arena lifetimes, no undefined behavior).
package native

import (
	"fmt"
	"strings"

	"brick/internal/ast"
	"brick/internal/checker"
)

// UnsupportedError reports a construct the native backend cannot lower yet.
type UnsupportedError struct{ Msg string }

func (e *UnsupportedError) Error() string {
	return fmt.Sprintf("native backend: %s (use --target c for now)", e.Msg)
}

var argRegs = []string{"%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9"}

type strConst struct {
	label string
	value string
}

// Gen holds state for one translation unit.
type Gen struct {
	types  map[ast.Expr]ast.Type
	b      strings.Builder
	rodata []strConst
	labelN int
	depth  int // temporaries currently pushed, in 8-byte units
	// per-function state
	scopes    []map[string]int // name -> rbp offset
	slotOf    map[*ast.VarStmt]int
	epilogue  string
	funcName  string
	frameSize int
}

// Generate lowers the program to x86-64 assembly, or returns an
// *UnsupportedError if it uses features without a native lowering yet.
func Generate(prog *ast.Program, ck *checker.Checker) (out string, err error) {
	g := &Gen{types: ck.Types}
	defer func() {
		if r := recover(); r != nil {
			if ue, ok := r.(*UnsupportedError); ok {
				out = ""
				err = ue
				return
			}
			panic(r)
		}
	}()

	g.line("# Generated by the Brick compiler (native x86-64 backend).")
	g.line("# System V AMD64 ABI.")
	g.line("  .text")

	emittedMain := false
	for _, s := range prog.Stmts {
		fd, ok := s.(*ast.FuncDecl)
		if !ok || fd.Body == nil {
			continue // structs, imports, and extern decls produce no code here
		}
		g.genFunc(fd)
		if fd.Name == "main" {
			emittedMain = true
		}
	}
	if !emittedMain {
		g.errorf("no main function to run")
	}

	g.line("")
	g.line("  .section .rodata")
	for _, s := range g.rodata {
		g.line(fmt.Sprintf("%s: .string %s", s.label, quote(s.value)))
	}
	g.line("")
	g.line("  .section .note.GNU-stack,\"\",@progbits")
	return g.b.String(), nil
}

func (g *Gen) errorf(format string, args ...any) {
	panic(&UnsupportedError{Msg: fmt.Sprintf(format, args...)})
}

func (g *Gen) line(s string) { g.b.WriteString(s); g.b.WriteByte('\n') }

func (g *Gen) newLabel(prefix string) string {
	g.labelN++
	return fmt.Sprintf(".L%s%d", prefix, g.labelN)
}

func (g *Gen) addString(val string) string {
	lbl := g.newLabel("str")
	g.rodata = append(g.rodata, strConst{label: lbl, value: val})
	return lbl
}

// ---------- functions ----------

func (g *Gen) genFunc(fd *ast.FuncDecl) {
	if len(fd.Params) > len(argRegs) {
		g.errorf("%s has more than %d parameters", fd.Name, len(argRegs))
	}
	for _, p := range fd.Params {
		g.checkScalarType(p.Type)
	}
	g.checkScalarType(fd.ReturnType)

	g.slotOf = map[*ast.VarStmt]int{}
	next := 0
	paramSlot := map[string]int{}
	for _, p := range fd.Params {
		paramSlot[p.Name] = next
		next++
	}
	g.assignSlots(fd.Body, &next)
	g.frameSize = roundUp(next*8, 16)

	g.funcName = fd.Name
	g.epilogue = g.newLabel("epi")
	g.scopes = nil
	g.enterScope()

	g.line("")
	g.line(".globl " + fd.Name)
	g.line(fd.Name + ":")
	g.line("  pushq %rbp")
	g.line("  movq %rsp, %rbp")
	if g.frameSize > 0 {
		g.line(fmt.Sprintf("  subq $%d, %%rsp", g.frameSize))
	}
	for i, p := range fd.Params {
		g.declare(p.Name, paramSlot[p.Name])
		g.line(fmt.Sprintf("  movq %s, %d(%%rbp)", argRegs[i], offset(paramSlot[p.Name])))
	}

	for _, st := range fd.Body.Stmts {
		g.genStmt(st)
	}
	if fd.Name == "main" {
		g.line("  movq $0, %rax") // default exit code
	}
	g.line(g.epilogue + ":")
	g.line("  movq %rbp, %rsp")
	g.line("  popq %rbp")
	g.line("  ret")
	g.exitScope()
}

// assignSlots gives every local variable a stack slot.
func (g *Gen) assignSlots(b *ast.BlockStmt, next *int) {
	for _, s := range b.Stmts {
		switch st := s.(type) {
		case *ast.VarStmt:
			g.slotOf[st] = *next
			*next++
		case *ast.BlockStmt:
			g.assignSlots(st, next)
		case *ast.IfStmt:
			g.assignSlots(st.Then, next)
			if eb, ok := st.Else.(*ast.BlockStmt); ok {
				g.assignSlots(eb, next)
			} else if ei, ok := st.Else.(*ast.IfStmt); ok {
				g.assignSlotsIf(ei, next)
			}
		case *ast.WhileStmt:
			g.assignSlots(st.Body, next)
		case *ast.ArenaStmt:
			g.assignSlots(st.Body, next)
		}
	}
}

func (g *Gen) assignSlotsIf(st *ast.IfStmt, next *int) {
	g.assignSlots(st.Then, next)
	if eb, ok := st.Else.(*ast.BlockStmt); ok {
		g.assignSlots(eb, next)
	} else if ei, ok := st.Else.(*ast.IfStmt); ok {
		g.assignSlotsIf(ei, next)
	}
}

func offset(slot int) int { return -8 * (slot + 1) }

func roundUp(n, to int) int {
	if n == 0 {
		return 0
	}
	return ((n + to - 1) / to) * to
}

// ---------- scopes ----------

func (g *Gen) enterScope() { g.scopes = append(g.scopes, map[string]int{}) }
func (g *Gen) exitScope()  { g.scopes = g.scopes[:len(g.scopes)-1] }

func (g *Gen) declare(name string, slot int) {
	g.scopes[len(g.scopes)-1][name] = slot
}

func (g *Gen) lookup(name string) (int, bool) {
	for i := len(g.scopes) - 1; i >= 0; i-- {
		if s, ok := g.scopes[i][name]; ok {
			return s, true
		}
	}
	return 0, false
}

// ---------- statements ----------

func (g *Gen) genStmt(s ast.Stmt) {
	switch st := s.(type) {
	case *ast.VarStmt:
		g.genExpr(st.Value)
		slot := g.slotOf[st]
		g.declare(st.Name, slot)
		g.line(fmt.Sprintf("  movq %%rax, %d(%%rbp)", offset(slot)))

	case *ast.AssignStmt:
		id, ok := st.Target.(*ast.Ident)
		if !ok {
			g.errorf("assignment to non-variable targets")
		}
		slot, ok := g.lookup(id.Name)
		if !ok {
			g.errorf("undefined variable %q", id.Name)
		}
		g.genExpr(st.Value)
		g.line(fmt.Sprintf("  movq %%rax, %d(%%rbp)", offset(slot)))

	case *ast.ExprStmt:
		g.genExpr(st.X)

	case *ast.ReturnStmt:
		if st.Value != nil {
			g.genExpr(st.Value)
		}
		g.line("  jmp " + g.epilogue)

	case *ast.BlockStmt:
		g.enterScope()
		for _, inner := range st.Stmts {
			g.genStmt(inner)
		}
		g.exitScope()

	case *ast.IfStmt:
		elseL := g.newLabel("else")
		endL := g.newLabel("endif")
		g.genExpr(st.Cond)
		g.line("  cmpq $0, %rax")
		g.line("  je " + elseL)
		g.genStmt(st.Then)
		g.line("  jmp " + endL)
		g.line(elseL + ":")
		if st.Else != nil {
			g.genStmt(st.Else)
		}
		g.line(endL + ":")

	case *ast.WhileStmt:
		startL := g.newLabel("while")
		endL := g.newLabel("endwhile")
		g.line(startL + ":")
		g.genExpr(st.Cond)
		g.line("  cmpq $0, %rax")
		g.line("  je " + endL)
		g.genStmt(st.Body)
		g.line("  jmp " + startL)
		g.line(endL + ":")

	case *ast.ArenaStmt:
		g.errorf("arena is not supported by the native backend yet")

	case *ast.BreakStmt, *ast.ContinueStmt:
		g.errorf("break/continue are not supported by the native backend yet")

	case *ast.ForStmt:
		g.errorf("for is not supported by the native backend yet")

	default:
		g.errorf("statement %T", s)
	}
}

// ---------- expressions ----------

// genExpr leaves the result in %rax and keeps the stack balanced.
func (g *Gen) genExpr(e ast.Expr) {
	switch ex := e.(type) {
	case *ast.IntLit:
		g.emitImm(ex.Value)
	case *ast.BoolLit:
		if ex.Value {
			g.line("  movq $1, %rax")
		} else {
			g.line("  xorl %eax, %eax")
		}
	case *ast.StringLit:
		lbl := g.addString(ex.Value)
		g.line(fmt.Sprintf("  leaq %s(%%rip), %%rax", lbl))
	case *ast.FloatLit:
		g.errorf("floating point is not supported yet")
	case *ast.Ident:
		slot, ok := g.lookup(ex.Name)
		if !ok {
			g.errorf("undefined variable %q", ex.Name)
		}
		g.line(fmt.Sprintf("  movq %d(%%rbp), %%rax", offset(slot)))
	case *ast.UnaryExpr:
		g.genUnary(ex)
	case *ast.BinaryExpr:
		g.genBinary(ex)
	case *ast.CallExpr:
		g.genCall(ex)
	case *ast.FieldExpr, *ast.StructLit:
		g.errorf("structs are not supported yet")
	case *ast.IndexExpr:
		g.errorf("indexing and List are not supported yet")
	default:
		g.errorf("expression %T", e)
	}
}

func (g *Gen) emitImm(v int64) {
	if v >= -2147483648 && v <= 2147483647 {
		g.line(fmt.Sprintf("  movq $%d, %%rax", v))
	} else {
		g.line(fmt.Sprintf("  movabsq $%d, %%rax", v))
	}
}

func (g *Gen) genUnary(ex *ast.UnaryExpr) {
	switch ex.Op {
	case "-":
		g.genExpr(ex.Operand)
		g.line("  negq %rax")
	case "!":
		g.genExpr(ex.Operand)
		g.line("  cmpq $0, %rax")
		g.line("  sete %al")
		g.line("  movzbq %al, %rax")
	case "&", "&mut":
		g.errorf("references are not supported yet")
	default:
		g.errorf("unary operator %q", ex.Op)
	}
}

func (g *Gen) genBinary(ex *ast.BinaryExpr) {
	if g.types[ex.Left].Name == "text" || g.types[ex.Right].Name == "text" {
		g.errorf("text operations are not supported yet")
	}
	switch ex.Op {
	case "&&":
		g.genShortCircuit(ex, true)
		return
	case "||":
		g.genShortCircuit(ex, false)
		return
	}

	g.genExpr(ex.Left)
	g.push()
	g.genExpr(ex.Right)
	g.line("  movq %rax, %rcx") // right
	g.line("  popq %rax")       // left
	g.depth--

	switch ex.Op {
	case "+":
		g.line("  addq %rcx, %rax")
	case "-":
		g.line("  subq %rcx, %rax")
	case "*":
		g.line("  imulq %rcx, %rax")
	case "/":
		g.line("  cqto")
		g.line("  idivq %rcx")
	case "%":
		g.line("  cqto")
		g.line("  idivq %rcx")
		g.line("  movq %rdx, %rax")
	case "<", "<=", ">", ">=", "==", "!=":
		g.line("  cmpq %rcx, %rax")
		g.line("  " + setcc(ex.Op) + " %al")
		g.line("  movzbq %al, %rax")
	default:
		g.errorf("binary operator %q", ex.Op)
	}
}

func setcc(op string) string {
	switch op {
	case "<":
		return "setl"
	case "<=":
		return "setle"
	case ">":
		return "setg"
	case ">=":
		return "setge"
	case "==":
		return "sete"
	case "!=":
		return "setne"
	}
	return "sete"
}

func (g *Gen) genShortCircuit(ex *ast.BinaryExpr, isAnd bool) {
	shortL := g.newLabel("sc")
	endL := g.newLabel("scend")
	g.genExpr(ex.Left)
	g.line("  cmpq $0, %rax")
	if isAnd {
		g.line("  je " + shortL)
	} else {
		g.line("  jne " + shortL)
	}
	g.genExpr(ex.Right)
	g.line("  cmpq $0, %rax")
	if isAnd {
		g.line("  je " + shortL)
	} else {
		g.line("  jne " + shortL)
	}
	// truthy result
	if isAnd {
		g.line("  movq $1, %rax")
	} else {
		g.line("  movq $1, %rax")
	}
	g.line("  jmp " + endL)
	g.line(shortL + ":")
	g.line("  xorl %eax, %eax")
	g.line(endL + ":")
}

func (g *Gen) genCall(ex *ast.CallExpr) {
	id, ok := ex.Callee.(*ast.Ident)
	if !ok {
		g.errorf("calls to computed values")
	}
	if id.Name == "print" {
		g.genPrint(ex.Args[0])
		return
	}
	switch id.Name {
	case "eprint", "print_bytes", "read_file", "write_file", "args", "List", "Map", "Builder", "to_text", "to_bytes", "bytes", "slice", "exit":
		g.errorf("%s is not supported by the native backend yet", id.Name)
	}
	if len(ex.Args) > len(argRegs) {
		g.errorf("%s has more than %d arguments", id.Name, len(argRegs))
	}
	// evaluate args left to right, pushing each; then pop into registers
	for _, a := range ex.Args {
		g.genExpr(a)
		g.push()
	}
	for i := len(ex.Args) - 1; i >= 0; i-- {
		g.line(fmt.Sprintf("  popq %s", argRegs[i]))
		g.depth--
	}
	g.callAligned(id.Name)
}

func (g *Gen) genPrint(arg ast.Expr) {
	t := g.types[arg]
	switch {
	case t.Equals(ast.Type{Name: "int"}):
		g.genExpr(arg)
		g.line("  movq %rax, %rsi")
		g.line(fmt.Sprintf("  leaq %s(%%rip), %%rdi", g.addString("%lld\n")))
		g.line("  xorl %eax, %eax") // no vector args
		g.callAligned("printf")
	case t.Equals(ast.Type{Name: "bool"}):
		falseL := g.newLabel("pfalse")
		endL := g.newLabel("pend")
		g.genExpr(arg)
		g.line("  cmpq $0, %rax")
		g.line("  je " + falseL)
		g.line(fmt.Sprintf("  leaq %s(%%rip), %%rdi", g.addString("true")))
		g.callAligned("puts")
		g.line("  jmp " + endL)
		g.line(falseL + ":")
		g.line(fmt.Sprintf("  leaq %s(%%rip), %%rdi", g.addString("false")))
		g.callAligned("puts")
		g.line(endL + ":")
	case t.Equals(ast.Type{Name: "text"}):
		g.genExpr(arg)
		g.line("  movq %rax, %rdi")
		g.callAligned("puts")
	default:
		g.errorf("print of type %s", t)
	}
}

// callAligned emits a call, keeping the stack 16-byte aligned per the ABI.
func (g *Gen) callAligned(fn string) {
	pad := g.depth%2 == 1
	if pad {
		g.line("  subq $8, %rsp")
	}
	g.line("  call " + fn)
	if pad {
		g.line("  addq $8, %rsp")
	}
}

func (g *Gen) push() {
	g.line("  pushq %rax")
	g.depth++
}

func (g *Gen) checkScalarType(t ast.Type) {
	if t.Ptr {
		g.errorf("references (%s) are not supported yet", t)
	}
	switch t.Name {
	case "int", "bool", "text", "void":
	default:
		g.errorf("type %q is not supported yet", t.Name)
	}
}

func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\n':
			b.WriteString("\\n")
		case '\t':
			b.WriteString("\\t")
		case '\r':
			b.WriteString("\\r")
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
